package Practicce;

public class Array_Default {
	
	public static void main(String[] args) {
		
		int[] arr=new int[2];
		String[] arr2=new String[3];
		float[] arr3=new float[4];
		char[] arr4=new char[3];
		
		System.out.println("Default value of Integer Array :"+arr[0]+" ," +arr[1]);
		System.out.println();
		System.out.println("Default value of String Array :"+arr2[0]+" ," +arr2[1] +" ," +arr2[2]);
		System.out.println();
		System.out.println("Default value of Float Array :"+arr3[0]+" ," +arr3[1] +arr3[2]+" ," +arr3[3]);
		System.out.println();
		System.out.println("Default value of Characterr Array :"+arr4[0]+" ," +arr4[1] + " ,"+arr4[2]);
	}

}
